_VAR_EPS_SQ = 1e-6   # Var_t(gt) threshold for a valid cell


def _decode_mask() -> tuple[np.ndarray, np.ndarray]:
    """Decode RLE literals → (mask int16 (nlat,nlon), lats float64 (nlat,))."""
    if not _MASK_RLE or _NLAT == 0:
        raise RuntimeError(
            "AR6 grid constants are empty. Run the notebook rasterize cell "
            "and paste the printed _NLAT/_NLON/_LATS/_MASK_RLE block into metric.py."
        )
    mask = np.repeat(
        np.array([v for v, _ in _MASK_RLE], dtype=np.int16),
        np.array([c for _, c in _MASK_RLE], dtype=np.int32),
    ).reshape(_NLAT, _NLON)
    lats = np.array(_LATS, dtype=np.float64)
    return mask, lats


def score(solution: pd.DataFrame, submission: pd.DataFrame, row_id_column_name: str) -> float:
    """
    Region-wise Normalized Nash-Sutcliffe Efficiency (nNSE).

    Returns the mean nNSE ∈ (−1, 1], averaged over AR6 land regions and variables.
    Higher is better.  nNSE = 0 means the model is no better than predicting
    the per-cell temporal mean.

    >>> import pandas as pd
    >>> import numpy as np
    >>> row_id_column_name = "row_id"
    >>> solution = pd.DataFrame({
    ...     "row_id": [0, 1, 2, 3],
    ...     "var1": [1.0, 2.0, 1.0, 2.0]
    ... })
    >>> submission = pd.DataFrame({
    ...     "row_id": [0, 1, 2, 3],
    ...     "var1": [1.5, 1.5, 1.5, 1.5]
    ... })
    >>> score(solution.copy(), submission.copy(), row_id_column_name)
    0.0
    """
    # ── Strip metadata columns ────────────────────────────────────────────
    metadata_columns = [row_id_column_name, "Usage"]
    solution = solution.drop(columns=metadata_columns, errors="ignore")
    submission = submission.drop(columns=metadata_columns, errors="ignore")

    missing_cols = set(solution.columns) - set(submission.columns)
    if missing_cols:
        raise ParticipantVisibleError(f"Submission is missing columns: {missing_cols}")

    for col in submission.columns:
        if not pd.api.types.is_numeric_dtype(submission[col]):
            raise ParticipantVisibleError(f"Submission column '{col}' must be numeric.")

    submission = submission[solution.columns]

    prediction_values = submission.to_numpy(dtype=np.float64, copy=False)
    if not np.isfinite(prediction_values).all():
        raise ParticipantVisibleError(
            "Submission contains NaN or infinite prediction values."
        )

    # ── Decode spatial grid ───────────────────────────────────────────────
    region_mask, lats = _decode_mask()        # (nlat, nlon) int16,  (nlat,) float64
    nlat, nlon = region_mask.shape
    n_rows = len(solution)

    # Kaggle invokes the metric with a tiny synthetic dataset when validating the
    # metric notebook. That dataset cannot be reshaped onto the competition grid,
    # so use a global (non-regional) nNSE only for that installation check. Real
    # competition submissions are required to contain complete 192×288 grids.
    if n_rows == 0 or n_rows % (nlat * nlon) != 0:
        var = solution.var(ddof=0)
        mse = ((solution - submission) ** 2).mean()
        valid = var > _VAR_EPS_SQ
        if not valid.any():
            return 0.0
        if not np.isfinite(mse[valid]).all():
            raise ParticipantVisibleError(
                "Submission contains values too large to score safely."
            )
        r2 = 1.0 - mse[valid] / var[valid]
        return float((r2 / (2.0 - r2)).mean())

    T = n_rows // (nlat * nlon)
    cos_w = np.cos(np.deg2rad(lats))                        # (nlat,)
    unique_regions = np.unique(region_mask[region_mask >= 0])

    # ── Compute per-variable region-wise nNSE ────────────────────────────
    per_var_scores: list = []

    for col in solution.columns:
        gt   = solution[col].values.astype(np.float64).reshape(T, nlat, nlon)
        pred = submission[col].values.astype(np.float64).reshape(T, nlat, nlon)

        var_cell = gt.var(axis=0)                            # (nlat, nlon)
        mse_cell = ((gt - pred) ** 2).mean(axis=0)          # (nlat, nlon)
        valid    = var_cell > _VAR_EPS_SQ                    # (nlat, nlon) bool

        if not np.isfinite(mse_cell[valid]).all():
            raise ParticipantVisibleError(
                f"Submission column '{col}' contains values too large to score safely."
            )

        r2_cell   = np.where(valid,
                             1.0 - mse_cell / np.maximum(var_cell, _VAR_EPS_SQ),
                             np.nan)
        nnse_cell = np.where(valid, r2_cell / (2.0 - r2_cell), np.nan)  # (nlat, nlon)

        region_nnse: list = []
        for rc in unique_regions:
            in_region = (region_mask == rc) & valid          # (nlat, nlon) bool
            w = cos_w[:, None] * in_region                   # (nlat, nlon) weights
            total_w = w.sum()
            if total_w < 1e-12:
                continue
            # Indexing first avoids relying on NaN-skipping reductions: invalid
            # and out-of-region cells are absent from both numerator and denominator.
            region_nnse.append(float(np.sum(nnse_cell[in_region] * w[in_region]) / total_w))

        if region_nnse:
            per_var_scores.append(float(np.mean(region_nnse)))

    if not per_var_scores:
        return 0.0

    return float(np.mean(per_var_scores))
